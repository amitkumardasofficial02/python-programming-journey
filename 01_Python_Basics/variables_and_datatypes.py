"""
Program: Python Variables and Data Types
Purpose: Understand different data types in Python.
Language: Python
"""

# Integer data type
age = 24

# Float data type
height = 5.9

# String data type
name = "Amit"

# Boolean data type
is_student = True

# Display variable values
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Student:", is_student)

# Identify the data types
print("\n--- Data Types ---")
print("Name:", type(name))
print("Age:", type(age))
print("Height:", type(height))
print("Student:", type(is_student))
